"""mdBook preprocessor: {{asset <path>}} -> link to a brand-day/ file plus a download button.

  {{asset templates/bryf-a4.svg}}          shows `brand-day/templates/bryf-a4.svg`
  {{asset templates/bryf-a4.svg short}}    shows `bryf-a4.svg`
  {{asset photos/01-kavobus/}}             folder: links to its section on the materials page, ⬇ downloads the zip

Files come from lessons/01-vstup/materialy/ (generated by tools/build_materials.py).
Registered in book.toml as [preprocessor.assets].
"""
import html, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'brand-day')
MAT = '01-vstup/materialy'          # generated folder, relative to the book source
PAGE = '01-vstup/materialy.html'    # materials page
MACRO = re.compile(r'\{\{asset ([^\s}]+)( short)?\}\}')


def zip_name(folder):
    """Archive built by build_materials.py for a folder (top level or photos/<theme>)."""
    return folder.strip('/').replace('/', '-') + '.zip'


def anchor(folder):
    return folder.strip('/').replace('/', '-')


def render(m, chapter_path):
    rel, short = m.group(1), bool(m.group(2))
    up = '../' * chapter_path.count('/')
    if not os.path.exists(os.path.join(SRC, rel)):
        sys.stderr.write(f'[assets] {chapter_path}: brand-day/{rel} does not exist\n')
    is_dir = rel.endswith('/')
    label = (os.path.basename(rel.rstrip('/')) + ('/' if is_dir else '')) if short else 'brand-day/' + rel
    if is_dir:
        view, dl, title = f'{up}{PAGE}#{anchor(rel)}', f'{up}{MAT}/zip/{zip_name(rel)}', 'Завантажити теку архівом'
        target = ''
    else:
        # mdBook does not copy .md files, so text files are served from a .txt copy
        view = dl = f'{up}{MAT}/' + (f'text/{rel[:-3]}.txt' if rel.endswith('.md') else f'brand-day/{rel}')
        title, target = 'Завантажити', ' target="_blank"'
    label = html.escape(label)
    return (f'<span class="asset"><a href="{view}"{target}><code>{label}</code></a>'
            f'<a class="asset-dl" href="{dl}" download title="{title}" aria-label="{title}: {label}">⬇</a></span>')


def walk(items):
    for it in items:
        ch = it.get('Chapter') if isinstance(it, dict) else None
        if ch:
            if ch.get('path'):
                ch['content'] = MACRO.sub(lambda m: render(m, ch['path']), ch['content'])
            walk(ch.get('sub_items', []))


if __name__ == '__main__':
    if len(sys.argv) > 1:  # "supports <renderer>"
        sys.exit(0)
    ctx, book = json.load(sys.stdin)
    walk(book.get('items') or book.get('sections') or [])
    json.dump(book, sys.stdout)
